#!/usr/bin/env bash
# Prints the Homebrew formula (Formula/mirante.rb in sirus-alpha-canis/homebrew-tap) for a
# released version: the prebuilt CLI, daemon, hook and MCP server for each Mac architecture.
# The release workflow runs it to update the tap; it is also how the formula is written by hand.
#
#   scripts/homebrew-formula.sh <version> <sha256 of aarch64 tarball> <sha256 of x86_64 tarball>
set -euo pipefail

if [ "$#" -ne 3 ]; then
  echo "usage: $0 <version> <sha256-aarch64-apple-darwin> <sha256-x86_64-apple-darwin>" >&2
  exit 2
fi
version="$1"
sha_arm="$2"
sha_intel="$3"
case "$version" in
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "version must look like 1.2.3 (no leading v): $version" >&2; exit 2 ;;
esac
for s in "$sha_arm" "$sha_intel"; do
  if ! printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$'; then
    echo "not a sha256: $s" >&2
    exit 2
  fi
done

base="https://github.com/sirus-alpha-canis/mirante/releases/download/v${version}"

cat <<EOF
# Generated by scripts/homebrew-formula.sh in sirus-alpha-canis/mirante; the release
# workflow rewrites this file on every release.
class Mirante < Formula
  desc "Local-first cockpit for dispatching and supervising coding agents"
  homepage "https://github.com/sirus-alpha-canis/mirante"
  version "${version}"
  license "Apache-2.0"

  on_arm do
    url "${base}/mirante-${version}-aarch64-apple-darwin.tar.gz"
    sha256 "${sha_arm}"
  end
  on_intel do
    url "${base}/mirante-${version}-x86_64-apple-darwin.tar.gz"
    sha256 "${sha_intel}"
  end

  livecheck do
    url :stable
    strategy :github_latest
  end

  depends_on :macos

  def install
    # The four binaries must sit in one directory: the CLI starts the mirante-daemon next to
    # it, and the daemon runs the mirante-hook and mirante-mcp next to it.
    bin.install "mirante", "mirante-daemon", "mirante-hook", "mirante-mcp"
    prefix.install "THIRD_PARTY_NOTICES.md"
  end

  def caveats
    <<~EOS
      Start the daemon (it has no window), then check the setup:
        mirante daemon start
        mirante doctor

      Mirante runs Claude Code and/or the Codex CLI, which must be installed and logged in.

      Homebrew installs mirante, mirante-daemon, mirante-hook and mirante-mcp together in its
      own prefix, so the daemon finds the hook and MCP server next to itself. After
      \`brew upgrade mirante\`, run \`mirante daemon restart\` once no task is running.

      The desktop app is not in Homebrew yet (it is unsigned). Build it from the repository
      with scripts/install.sh --app (needs rustup, Node 22.12+ and pnpm 10):
        git clone https://github.com/sirus-alpha-canis/mirante.git
        cd mirante && scripts/install.sh --app
      install.sh also links its own build of the binaries into ~/.local/bin. Keep one copy
      on your PATH: either this formula or install.sh (scripts/uninstall.sh removes its links).
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mirante --version")
    assert_match version.to_s, shell_output("#{bin}/mirante-daemon --version")
    assert_match "daemon", shell_output("#{bin}/mirante help")
  end
end
EOF
